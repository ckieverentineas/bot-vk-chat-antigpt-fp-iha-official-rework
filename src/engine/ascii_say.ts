export function parseAsciiSayCommand(message: string): string | undefined {
    const match = message.match(/^!(?:скажи|say)(?:\s+([\s\S]*))?$/i);

    if (!match) {
        return undefined;
    }

    return match[1]?.trim() ?? '';
}

export function validateAsciiSayText(input: string): SayTextValidation {
    const text = normalizeAsciiSayText(input);

    if (!text) {
        return { ok: false, reason: 'Напишите текст после команды, например: !скажи привет' };
    }

    if (text.length > MAX_INPUT_LENGTH) {
        return { ok: false, reason: `Слишком длинно. Максимум ${MAX_INPUT_LENGTH} символов.` };
    }

    if (text.split('\n').length > MAX_INPUT_LINES) {
        return { ok: false, reason: `Слишком много строк. Максимум ${MAX_INPUT_LINES}.` };
    }

    if (containsUnsafeBroadcastPattern(text)) {
        return { ok: false, reason: 'Текст не прошел фильтр безопасности.' };
    }

    const unsupportedCharacters = getUnsupportedCharacters(text);
    if (unsupportedCharacters.length > 0) {
        return {
            ok: false,
            reason: `Не умею рисовать символы: ${unsupportedCharacters.join(' ')}`,
        };
    }

    return { ok: true, text };
}

export function buildAsciiSayMessage(text: string): string {
    const renderedLines = text
        .split('\n')
        .flatMap((line, index, lines) => {
            const renderedLine = renderAsciiLine(line);

            if (index === lines.length - 1) {
                return renderedLine;
            }

            return [...renderedLine, ''];
        });

    const output = renderedLines.join('\n').slice(0, MAX_OUTPUT_LENGTH);

    return ['```', output, '```'].join('\n');
}

function normalizeAsciiSayText(input: string): string {
    return input
        .replace(/\r\n/g, '\n')
        .replace(/\r/g, '\n')
        .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
        .split('\n')
        .map(line => line.replace(/\s+/g, ' ').trim())
        .join('\n')
        .trim();
}

function containsUnsafeBroadcastPattern(text: string): boolean {
    return [
        /https?:\/\//i,
        /\bwww\./i,
        /\bvk\.com\b/i,
        /\bt\.me\b/i,
        /\[(?:id|club|public)\d+\|/i,
        /@[a-z0-9_.-]+/i,
        /\d(?:[\s-]?\d){7,}/,
    ].some(pattern => pattern.test(text));
}

function getUnsupportedCharacters(text: string): string[] {
    const unsupported = new Set<string>();

    for (const character of text) {
        if (character === '\n') {
            continue;
        }

        if (!getGlyph(character)) {
            unsupported.add(character);
        }
    }

    return [...unsupported];
}

function renderAsciiLine(line: string): string[] {
    const glyphHeight = 7;
    const rows: string[] = Array.from({ length: glyphHeight }, () => '');

    for (const character of line) {
        const glyph = getGlyph(character);

        if (!glyph) {
            continue;
        }

        glyph.forEach((row, index) => {
            rows[index] += `${row.replace(/1/g, '#').replace(/0/g, ' ')}  `;
        });
    }

    return rows.map(row => row.replace(/\s+$/g, ''));
}

function getGlyph(character: string): Glyph | undefined {
    return glyphs[character] ?? glyphs[aliases[character] ?? character.toUpperCase()];
}
